"""Tracker hygiene sweep (#368 C.2). Dry-run by default.

  python3 tooling/roadmap/hygiene.py            # fetch the tracker, print what it would do and what it only reports
  python3 tooling/roadmap/hygiene.py --apply    # do the routine part (below), still only reports the rest

Does (routine, ORCHESTRATION.md "unblock procedure" and AGENTS.md §8 closure):
  unblock  open lot, every numeric dependency closed, not captured-blocked, not claimed -> `status: ready`
           (drops `status: blocked`), comment `Unblocked by #PR`; an engine lot also gets `external: ready`
  close    merged dev-swift PR with `Closes #N` whose issue is still open -> `Done in #PR (merged as <sha>)`, close
Only reports (never changes): claims silent for 72 h, several labels on one axis, no status, `ready`+`claimed`,
ready lots with an open dependency, ready engine lots without `external: ready`, unblocks with no known PR.
Needs `gh` (or run after `sync_state.py` for the lots/state files). Reads lots.json: refresh it first with
lots_from_md.py when LOTS.md changed.
"""
import json
import re
import subprocess
import sys
from datetime import datetime, timedelta, timezone
from pathlib import Path

from sync_state import REPO, build, gh_pages, labels

HERE = Path(__file__).resolve().parent
FOOT = '\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_'
AXES = ('type', 'priority', 'difficulty', 'status', 'area')
ENGINE = re.compile(r'^HFR\w+')
CLOSES = re.compile(r'\b(?:close[sd]?|fix(?:e[sd])?|resolve[sd]?)\s+#(\d+)', re.I)
STALE = timedelta(hours=72)


def numeric_deps(cell):
    """Lot numbers in a Depends-on cell; None when the cell is a gate sentence ("all parsing lots")."""
    if cell.strip() in ('—', '-', ''):
        return []
    nums = re.findall(r'\b\d{3}\b', cell)
    return ['LOT-' + n for n in nums] if nums else None


def ts(s):
    return datetime.fromisoformat(s.replace('Z', '+00:00'))


def analyze(issues, pulls, lots, comments, now):
    """Return (actions, reports). `comments` maps issue number -> list of comment dicts (claimed issues only)."""
    real = [i for i in issues if 'pull_request' not in i]
    by_n = {i['number']: i for i in real}
    by_lot = {r['lot']: r for r in lots}
    st = build(issues, pulls, lots)
    closed, claimed_set = set(st['closed']), set(st['claimed'])
    capture = {int(k) for k in st['capture']}
    actions, reports = [], []

    # merged PR -> issues it closes (dev-swift only); last merge wins for "Unblocked by"
    merged = sorted((p for p in pulls if p.get('merged_at') and (p.get('base') or {}).get('ref') == 'dev-swift'),
                    key=lambda p: p['merged_at'])
    closer = {}
    for p in merged:
        for m in CLOSES.findall(p.get('body') or ''):
            closer[int(m)] = p
    for n, p in sorted(closer.items()):
        i = by_n.get(n)
        if i and i['state'].lower() == 'open':
            actions.append({'kind': 'close', 'issue': n, 'pr': p['number'], 'sha': (p.get('merge_commit_sha') or '')[:7]})

    gate = []
    pending_close = {a['issue'] for a in actions if a['kind'] == 'close'}
    for r in lots:
        n = r['issue']
        i = by_n.get(n)
        if not i or i['state'].lower() != 'open':
            continue
        lb = labels(i)
        deps = numeric_deps(r['deps'])
        dep_issues = [by_lot[d]['issue'] for d in (deps or []) if d in by_lot]
        open_deps = [d for d in dep_issues if d not in closed]
        if 'status: ready' in lb and open_deps:
            reports.append(f"#{n} {r['lot']} is `status: ready` but depends on open " + ', '.join(f'#{d}' for d in open_deps))
        if deps is None and 'status: blocked' in lb and n not in capture:
            gate.append(f"{r['lot']} #{n}")
        if deps is None or 'status: ready' in lb or 'status: claimed' in lb or open_deps or n in capture or n in pending_close:
            continue
        if 'status: blocked' not in lb and 'status: needs-triage' not in lb:
            continue
        pr = max((closer[d] for d in dep_issues if d in closer), key=lambda p: p['merged_at'], default=None)
        if not dep_issues:
            continue  # no dependency to credit: a plain blocked lot with no cause, left to triage
        if pr is None:
            reports.append(f"#{n} {r['lot']}: dependencies done but no merged PR found to credit, unblock by hand")
            continue
        ext = bool(ENGINE.match(r['module'])) and 'host: mac' not in lb
        actions.append({'kind': 'unblock', 'issue': n, 'lot': r['lot'], 'pr': pr['number'], 'external': ext})

    if gate:
        reports.append('blocked lots with a gate sentence as dependency (resolve by hand): ' + ', '.join(gate))
    for i in real:
        if i['state'].lower() != 'open':
            continue
        n, lb = i['number'], labels(i)
        if not any(x.startswith('type: ') for x in lb):
            continue
        for ax in AXES:
            got = sorted(x for x in lb if x.startswith(ax + ': '))
            if len(got) > 1:
                reports.append(f'#{n}: {len(got)} labels on axis `{ax}` ({", ".join(got)})')
        if not any(x.startswith('status: ') for x in lb) and not any(x == 'type: roadmap' for x in lb):
            reports.append(f'#{n}: no `status:` label')
        if 'status: ready' in lb and 'status: claimed' in lb:
            reports.append(f'#{n}: both `status: ready` and `status: claimed`')
    for n in sorted(claimed_set):
        cs = comments.get(n) or []
        last = max([ts(c['created_at']) for c in cs] + [ts(by_n[n]['created_at'])]) if n in by_n else None
        if last and now - last > STALE:
            reports.append(f'#{n}: claimed, silent for {(now - last).days} days (orchestrator decides, never released by the sweep)')
    lot_by_issue = {r['issue']: r for r in lots}
    cand = [n for n in sorted(st['ready']) if n in lot_by_issue and ENGINE.match(lot_by_issue[n]['module'])
            and n not in st['external'] and 'host: mac' not in labels(by_n[n])]
    if cand:
        reports.append('ready engine lots without `external: ready` (operator opens them): ' + ', '.join(f'#{n}' for n in cand))
    return actions, reports


def gh(method, path, fields=()):
    cmd = ['gh', 'api', '-X', method, path]
    for f in fields:
        cmd += ['-f', f]
    r = subprocess.run(cmd, capture_output=True, text=True)
    if r.returncode:
        raise RuntimeError(r.stderr.strip()[:200])


def apply(actions, by_n):
    for a in actions:
        n = a['issue']
        base = f'repos/{REPO}/issues/{n}'
        if a['kind'] == 'unblock':
            lb = sorted((labels(by_n[n]) - {'status: blocked', 'status: needs-triage'}) | {'status: ready'} | ({'external: ready'} if a['external'] else set()))
            gh('PATCH', base, fields=[f'labels[]={x}' for x in lb])
            gh('POST', base + '/comments', fields=[f"body=Unblocked by #{a['pr']}{FOOT}"])
        else:
            gh('POST', base + '/comments', fields=[f"body=Done in #{a['pr']} (merged as {a['sha']}){FOOT}"])
            gh('PATCH', base, fields=['state=closed', 'state_reason=completed'])
        print('applied', a)


if __name__ == '__main__':
    do_apply = '--apply' in sys.argv[1:]
    lots = json.load(open(HERE / 'lots.json', encoding='utf-8'))
    issues = gh_pages(f'repos/{REPO}/issues?state=all')
    pulls = gh_pages(f'repos/{REPO}/pulls?state=all&base=dev-swift')
    st = build(issues, pulls, lots)
    comments = {n: gh_pages(f'repos/{REPO}/issues/{n}/comments') for n in st['claimed']}
    actions, reports = analyze(issues, pulls, lots, comments, datetime.now(timezone.utc))
    print(f'== {len(actions)} routine action(s) ({"APPLYING" if do_apply else "dry-run"})')
    for a in actions:
        print(' ', a)
    print(f'== {len(reports)} report(s) for the orchestrator')
    for x in reports:
        print(' -', x)
    if do_apply:
        apply(actions, {i['number']: i for i in issues})
