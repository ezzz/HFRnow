def pct(ms):
    d,o,t,tot=counts(ms); return d,o,t,tot,round(100*d/tot)
def special(l,st):
    if l=='LOT-070': return '⛔ waits on every engine lot (gate)'
    return st
def tbl(ls,cols):
    out=['| '+' | '.join(cols)+' |','|'+'---|'*len(cols)]
    for l in sorted(ls,key=n):
        r=rows[l]
        d={'Lot':f"**{l}** #{r['issue']}",'Deliverable':short(r['scope'],80),'State':special(l,state(l)[1]),
           'Flavor':flavor(r),'Routing':r['model'].replace(' → ','→')}
        out.append('| '+' | '.join(d[c] for c in cols)+' |')
    return '\n'.join(out)
def by_theme(ls):
    g={}
    for l in ls:
        r=rows[l]; t=(r['sub'] or r['sec'].split('—')[-1]).split('(')[0].replace('app: ','').strip()
        g.setdefault(t,[]).append(l)
    return g
def board(ms,title,emoji):
    b={'todo':[],'ongoing':[],'done':[]}
    for l in ms: b[state(l)[0]].append(l)
    d,o,t,tot,p=pct(ms)
    s=[f'## {emoji} {title}\n',f'{bar(d,tot)} **{p} %** · ✅ {d} done · 🔄 {o} ongoing · 🔜 {t} todo · {tot} lots\n']
    s.append(f'### 🔄 Ongoing ({len(b["ongoing"])})\n')
    s.append(tbl(b['ongoing'],['Lot','Deliverable','State','Routing']) if b['ongoing'] else '_None._')
    s.append(f'\n### 🔜 Todo ({len(b["todo"])})\n')
    for th,ls in sorted(by_theme(b['todo']).items()):
        s.append(f'**{th}**\n'); s.append(tbl(ls,['Lot','Deliverable','State','Flavor','Routing'])); s.append('')
    if b['done']:
        s.append(f'<details><summary>✅ Done ({len(b["done"])})</summary>\n')
        s.append(', '.join(f"{l} #{rows[l]['issue']}" for l in sorted(b['done'],key=n)))
        s.append('\n</details>\n')
    else: s.append('### ✅ Done (0)\n')
    return '\n'.join(s)
